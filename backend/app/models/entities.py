from datetime import datetime
from sqlalchemy import (
    Column,
    String,
    Integer,
    Numeric,
    Boolean,
    DateTime,
    ForeignKey,
    Text,
    Index,
)
from sqlalchemy.orm import relationship
from app.core.database import Base
from app.models.base import UUIDPrimaryKeyMixin, TimestampMixin


class User(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Application users with role-based access control."""
    __tablename__ = "users"

    email = Column(String(255), unique=True, index=True, nullable=False)
    password_hash = Column(String(255), nullable=False)
    role = Column(String(50), default="user", nullable=False)  # 'user', 'analyst', 'admin'
    is_active = Column(Boolean, default=True, nullable=False)

    wallets = relationship("Wallet", back_populates="user", cascade="all, delete-orphan")
    audit_events = relationship("AuditEvent", back_populates="actor")


class Wallet(Base, UUIDPrimaryKeyMixin):
    """Registered public wallet addresses."""
    __tablename__ = "wallets"

    user_id = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    address = Column(String(66), index=True, nullable=False)
    chain_id = Column(Integer, default=1, nullable=False)
    label = Column(String(100), nullable=True)
    connected_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    user = relationship("User", back_populates="wallets")
    transactions = relationship("Transaction", back_populates="wallet")
    risk_analyses = relationship("RiskAnalysis", back_populates="wallet")
    alerts = relationship("Alert", back_populates="wallet")


class Asset(Base, UUIDPrimaryKeyMixin):
    """Supported cryptocurrency and DeFi token metadata."""
    __tablename__ = "assets"

    symbol = Column(String(20), unique=True, index=True, nullable=False)
    name = Column(String(100), nullable=False)
    decimals = Column(Integer, default=18, nullable=False)
    chain_id = Column(Integer, default=1, nullable=False)
    contract_address = Column(String(66), nullable=True)

    transactions = relationship("Transaction", back_populates="asset")
    price_snapshots = relationship("PriceSnapshot", back_populates="asset")


class Transaction(Base, UUIDPrimaryKeyMixin):
    """On-chain or simulated financial transaction records."""
    __tablename__ = "transactions"

    wallet_id = Column(String(36), ForeignKey("wallets.id", ondelete="SET NULL"), nullable=True)
    tx_hash = Column(String(66), unique=True, index=True, nullable=False)
    chain_id = Column(Integer, default=1, nullable=False)
    from_address = Column(String(66), index=True, nullable=False)
    to_address = Column(String(66), index=True, nullable=False)
    asset_id = Column(String(36), ForeignKey("assets.id", ondelete="RESTRICT"), nullable=True)
    amount = Column(Numeric(precision=36, scale=18), nullable=False)
    timestamp = Column(DateTime, default=datetime.utcnow, index=True, nullable=False)
    status = Column(String(20), default="completed", nullable=False)  # pending, completed, failed
    block_number = Column(Integer, nullable=True)

    wallet = relationship("Wallet", back_populates="transactions")
    asset = relationship("Asset", back_populates="transactions")
    risk_analyses = relationship("RiskAnalysis", back_populates="transaction")
    alerts = relationship("Alert", back_populates="transaction")


class PriceSnapshot(Base, UUIDPrimaryKeyMixin):
    """Historical or real-time asset price snapshots with provenance."""
    __tablename__ = "price_snapshots"

    asset_id = Column(String(36), ForeignKey("assets.id", ondelete="CASCADE"), nullable=False)
    price = Column(Numeric(precision=24, scale=8), nullable=False)
    currency = Column(String(10), default="USD", nullable=False)
    source = Column(String(50), default="coingecko", nullable=False)
    observed_at = Column(DateTime, default=datetime.utcnow, index=True, nullable=False)

    asset = relationship("Asset", back_populates="price_snapshots")


class RiskAnalysis(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Auditable risk assessment results generated by rules or ML pipelines."""
    __tablename__ = "risk_analyses"

    wallet_id = Column(String(36), ForeignKey("wallets.id", ondelete="SET NULL"), nullable=True)
    transaction_id = Column(String(36), ForeignKey("transactions.id", ondelete="SET NULL"), nullable=True)
    model_name = Column(String(100), default="isolation_forest", nullable=False)
    model_version = Column(String(50), default="1.0.0", nullable=False)
    score = Column(Numeric(precision=5, scale=2), nullable=False)  # 0.00 to 100.00
    risk_band = Column(String(20), nullable=False)  # low, medium, high, critical
    reasons_json = Column(Text, nullable=True)  # JSON-encoded array of signals

    wallet = relationship("Wallet", back_populates="risk_analyses")
    transaction = relationship("Transaction", back_populates="risk_analyses")


class Alert(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Compliance and risk alerts requiring monitoring or human review."""
    __tablename__ = "alerts"

    wallet_id = Column(String(36), ForeignKey("wallets.id", ondelete="SET NULL"), nullable=True)
    transaction_id = Column(String(36), ForeignKey("transactions.id", ondelete="SET NULL"), nullable=True)
    rule_code = Column(String(50), nullable=False)
    severity = Column(String(20), default="medium", nullable=False)  # low, medium, high, critical
    status = Column(String(20), default="open", nullable=False)  # open, under_review, resolved, dismissed
    summary = Column(String(255), nullable=False)

    wallet = relationship("Wallet", back_populates="alerts")
    transaction = relationship("Transaction", back_populates="alerts")
    compliance_cases = relationship("ComplianceCase", back_populates="alert")


class ComplianceCase(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """RegTech compliance case management records."""
    __tablename__ = "compliance_cases"

    alert_id = Column(String(36), ForeignKey("alerts.id", ondelete="CASCADE"), nullable=False)
    assigned_to = Column(String(255), nullable=True)
    status = Column(String(30), default="open", nullable=False)  # open, investigating, closed, escalated
    reviewer_notes = Column(Text, nullable=True)
    decision = Column(String(50), nullable=True)  # cleared, sar_filed, restricted
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow, nullable=False)

    alert = relationship("Alert", back_populates="compliance_cases")


class ContractScan(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Smart contract static analysis scan metadata."""
    __tablename__ = "contract_scans"

    submitted_name = Column(String(255), nullable=False)
    source_hash = Column(String(64), nullable=False)
    tool_name = Column(String(50), default="slither", nullable=False)
    tool_version = Column(String(50), default="0.10.0", nullable=False)
    status = Column(String(30), default="completed", nullable=False)

    findings = relationship("ContractFinding", back_populates="scan", cascade="all, delete-orphan")


class ContractFinding(Base, UUIDPrimaryKeyMixin):
    """Individual security findings detected during contract scanning."""
    __tablename__ = "contract_findings"

    scan_id = Column(String(36), ForeignKey("contract_scans.id", ondelete="CASCADE"), nullable=False)
    detector = Column(String(100), nullable=False)
    severity = Column(String(20), nullable=False)  # high, medium, low, informational
    file_path = Column(String(255), nullable=True)
    line_number = Column(Integer, nullable=True)
    description = Column(Text, nullable=False)
    recommendation = Column(Text, nullable=True)

    scan = relationship("ContractScan", back_populates="findings")


class AuditEvent(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Append-only audit trail for administrative and risk review actions."""
    __tablename__ = "audit_events"

    actor_user_id = Column(String(36), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    action = Column(String(100), nullable=False)
    entity_type = Column(String(50), nullable=False)
    entity_id = Column(String(36), nullable=True)
    metadata_json = Column(Text, nullable=True)

    actor = relationship("User", back_populates="audit_events")


class Proposal(Base, UUIDPrimaryKeyMixin):
    """DAO governance proposal demonstration."""
    __tablename__ = "proposals"

    proposer_wallet = Column(String(66), nullable=False)
    title = Column(String(255), nullable=False)
    description = Column(Text, nullable=False)
    start_at = Column(DateTime, nullable=False)
    end_at = Column(DateTime, nullable=False)
    status = Column(String(20), default="active", nullable=False)  # pending, active, passed, rejected

    votes = relationship("Vote", back_populates="proposal", cascade="all, delete-orphan")


class Vote(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """DAO governance votes cast on proposals."""
    __tablename__ = "votes"

    proposal_id = Column(String(36), ForeignKey("proposals.id", ondelete="CASCADE"), nullable=False)
    voter_wallet = Column(String(66), nullable=False)
    voting_power = Column(Numeric(precision=36, scale=18), nullable=False)
    choice = Column(String(10), nullable=False)  # for, against, abstain

    proposal = relationship("Proposal", back_populates="votes")
