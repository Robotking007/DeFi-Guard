import secrets
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from eth_account import Account
from eth_account.messages import encode_defunct

from app.core.database import get_db
from app.core.security import get_password_hash, verify_password, create_access_token
from app.models.entities import User, Wallet, AuditEvent
from app.schemas.auth import (
    LoginRequest,
    RegisterRequest,
    Token,
    NonceResponse,
    SIWEVerifyRequest,
    Web3AuthLoginRequest,
)
from app.schemas.user import UserResponse

router = APIRouter(prefix="/auth", tags=["Authentication"])


@router.post("/register", response_model=UserResponse, status_code=status.HTTP_201_CREATED)
def register(request: RegisterRequest, db: Session = Depends(get_db)):
    """Register a new user account with specified role."""
    existing = db.query(User).filter(User.email == request.email).first()
    if existing:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Email is already registered.",
        )

    user = User(
        email=request.email,
        password_hash=get_password_hash(request.password),
        role=request.role,
        is_active=True,
    )
    db.add(user)
    db.commit()
    db.refresh(user)

    # Log audit event
    audit = AuditEvent(
        actor_user_id=user.id,
        action="USER_REGISTERED",
        entity_type="user",
        entity_id=user.id,
        metadata_json=f'{{"email": "{user.email}", "role": "{user.role}"}}',
    )
    db.add(audit)
    db.commit()

    return user


@router.post("/login", response_model=Token)
def login(request: LoginRequest, db: Session = Depends(get_db)):
    """Authenticate credentials and generate signed JWT access token."""
    user = db.query(User).filter(User.email == request.email).first()
    if not user or not verify_password(request.password, user.password_hash):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid email or password.",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not user.is_active:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Account is deactivated.",
        )

    access_token = create_access_token(
        data={"sub": user.id, "email": user.email, "role": user.role}
    )

    # Log audit event
    audit = AuditEvent(
        actor_user_id=user.id,
        action="USER_LOGIN",
        entity_type="user",
        entity_id=user.id,
    )
    db.add(audit)
    db.commit()

    return Token(
        access_token=access_token,
        token_type="bearer",
        role=user.role,
        email=user.email,
    )


@router.get("/nonce", response_model=NonceResponse)
def get_siwe_nonce():
    """Generate a random cryptographic challenge nonce for Sign-In with Ethereum."""
    nonce = secrets.token_hex(16)
    return NonceResponse(nonce=nonce)


@router.post("/siwe/verify", response_model=Token)
def verify_siwe(request: SIWEVerifyRequest, db: Session = Depends(get_db)):
    """
    Verify an EIP-4361 / SIWE digital signature generated by MetaMask or Web3 provider.
    Proves true cryptographic ownership of the private key without passwords.
    """
    try:
        encoded_message = encode_defunct(text=request.message)
        recovered_address = Account.recover_message(encoded_message, signature=request.signature)
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Cryptographic signature verification failed: {str(e)}",
        )

    if recovered_address.lower() != request.address.lower():
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Signature recovered address ({recovered_address}) does not match requested address ({request.address}).",
        )

    # Find existing wallet or user
    wallet = db.query(Wallet).filter(Wallet.address.ilike(request.address)).first()
    if wallet and wallet.user:
        user = wallet.user
    else:
        # Create user account for this on-chain wallet
        wallet_email = f"{request.address.lower()[:10]}@wallet.defiguard.io"
        user = db.query(User).filter(User.email == wallet_email).first()
        if not user:
            user = User(
                email=wallet_email,
                password_hash=get_password_hash(secrets.token_urlsafe(32)),
                role="user",
                is_active=True,
            )
            db.add(user)
            db.flush()

        if not wallet:
            wallet = Wallet(
                user_id=user.id,
                address=request.address,
                chain_id=11155111,
                label="MetaMask / Web3Auth Primary",
            )
            db.add(wallet)

        db.commit()

    # Log SIWE audit event
    audit = AuditEvent(
        actor_user_id=user.id,
        action="SIWE_AUTHENTICATED",
        entity_type="wallet",
        entity_id=wallet.id if wallet else None,
        metadata_json=f'{{"address": "{request.address}", "method": "EIP-4361"}}',
    )
    db.add(audit)
    db.commit()

    access_token = create_access_token(
        data={"sub": user.id, "email": user.email, "role": user.role}
    )

    return Token(
        access_token=access_token,
        token_type="bearer",
        role=user.role,
        email=user.email,
    )


@router.post("/web3auth", response_model=Token)
def verify_web3auth(request: Web3AuthLoginRequest, db: Session = Depends(get_db)):
    """
    Authenticate a session initialized via Web3Auth Sapphire Devnet.
    Supports MetaMask, Coinbase, and Social Logins (Google/GitHub non-custodial EVM wallets).
    """
    addr = request.public_address.lower()
    email = request.email or f"{addr[:10]}@web3auth.defiguard.io"

    # Find or create user
    user = db.query(User).filter(User.email == email).first()
    if not user:
        user = User(
            email=email,
            password_hash=get_password_hash(secrets.token_urlsafe(32)),
            role="user",
            is_active=True,
        )
        db.add(user)
        db.flush()

    # Ensure wallet is registered
    wallet = db.query(Wallet).filter(Wallet.address.ilike(addr)).first()
    if not wallet:
        wallet = Wallet(
            user_id=user.id,
            address=request.public_address,
            chain_id=11155111,
            label="Web3Auth Sapphire Devnet Wallet",
        )
        db.add(wallet)
        db.commit()

    audit = AuditEvent(
        actor_user_id=user.id,
        action="WEB3AUTH_LOGIN",
        entity_type="wallet",
        entity_id=wallet.id,
        metadata_json=f'{{"address": "{addr}", "email": "{email}"}}',
    )
    db.add(audit)
    db.commit()

    access_token = create_access_token(
        data={"sub": user.id, "email": user.email, "role": user.role}
    )

    return Token(
        access_token=access_token,
        token_type="bearer",
        role=user.role,
        email=user.email,
    )
